//! Request and response bodies. All binary fields are standard base64.

use serde::{Deserialize, Serialize};

use crate::hsm::{KeyInfo, KeyKind, PoolStats, SigningAlgorithm, WrapRoundtrip};

/// Encoding of an ECDSA signature. Ignored (always `raw`) for RSA-PSS and
/// Ed25519, whose signatures have a single canonical encoding.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum SignatureFormat {
    /// ASN.1 DER `SEQUENCE { r INTEGER, s INTEGER }` (X.509 / TLS form).
    #[default]
    Der,
    /// Fixed-width `r || s` as returned by PKCS#11.
    Raw,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SignRequest {
    pub key_id: String,
    pub algorithm: SigningAlgorithm,
    /// Base64 payload to sign.
    pub payload: String,
    #[serde(default)]
    pub signature_format: SignatureFormat,
}

#[derive(Debug, Serialize)]
pub struct SignResponse {
    pub key_id: String,
    pub algorithm: SigningAlgorithm,
    pub signature: String,
    pub signature_format: SignatureFormat,
    pub duration_ms: f64,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct VerifyRequest {
    pub key_id: String,
    pub algorithm: SigningAlgorithm,
    pub payload: String,
    pub signature: String,
    #[serde(default)]
    pub signature_format: SignatureFormat,
}

#[derive(Debug, Serialize)]
pub struct VerifyResponse {
    pub key_id: String,
    pub algorithm: SigningAlgorithm,
    pub valid: bool,
    pub duration_ms: f64,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct EncryptRequest {
    pub key_id: String,
    /// Base64 plaintext.
    pub plaintext: String,
    /// Optional base64 additional authenticated data.
    #[serde(default)]
    pub aad: Option<String>,
}

#[derive(Debug, Serialize)]
pub struct EncryptResponse {
    pub key_id: String,
    pub algorithm: &'static str,
    /// Base64, 12 bytes, generated by the token.
    pub iv: String,
    /// Base64 `ciphertext || 16-byte tag`.
    pub ciphertext: String,
    pub duration_ms: f64,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct DecryptRequest {
    pub key_id: String,
    pub iv: String,
    pub ciphertext: String,
    #[serde(default)]
    pub aad: Option<String>,
}

#[derive(Debug, Serialize)]
pub struct DecryptResponse {
    pub key_id: String,
    pub plaintext: String,
    pub duration_ms: f64,
}

#[derive(Debug, Serialize)]
pub struct KeysResponse {
    pub keys: Vec<KeyInfo>,
}

#[derive(Debug, Serialize)]
pub struct PublicKeyResponse {
    pub key_id: String,
    pub kind: KeyKind,
    pub algorithms: Vec<SigningAlgorithm>,
    /// PEM-encoded `SubjectPublicKeyInfo`.
    pub public_key_pem: String,
}

pub type WrapRoundtripResponse = WrapRoundtrip;

#[derive(Debug, Serialize)]
pub struct HealthResponse {
    pub status: &'static str,
    pub uptime_s: u64,
}

#[derive(Debug, Serialize)]
pub struct ReadyResponse {
    pub status: &'static str,
    pub backend: &'static str,
    pub pool: PoolStats,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error: Option<&'static str>,
}

#[derive(Debug, Serialize)]
pub struct ErrorBody {
    pub error: ErrorDetail,
}

#[derive(Debug, Serialize)]
pub struct ErrorDetail {
    pub code: &'static str,
    pub message: String,
}
